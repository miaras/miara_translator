import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output = process.env.LAUNCH_WORK_DIR || '/tmp/shiroko-launch';
await mkdir(`${output}/raw`, {recursive:true});
const passage = (await readFile(new URL('./passage.txt', import.meta.url),'utf8')).trim();
const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
const context = await browser.newContext({viewport:{width:1440,height:900}, recordVideo:{dir:`${output}/raw`,size:{width:1440,height:900}}, permissions:['clipboard-read','clipboard-write']});
await context.addInitScript(() => {
 document.addEventListener('DOMContentLoaded',()=>{
  const cursor=document.createElement('div');
  cursor.style.cssText='position:fixed;left:-100px;top:-100px;width:18px;height:18px;border:2px solid #d4edf8;border-radius:50%;background:#83b6ce55;box-shadow:0 0 0 5px #83b6ce22;pointer-events:none;z-index:99999;transform:translate(-50%,-50%)';
  document.body.append(cursor);
  document.addEventListener('mousemove',e=>{cursor.style.left=`${e.clientX}px`;cursor.style.top=`${e.clientY}px`;});
  document.addEventListener('mousedown',()=>cursor.style.background='#d4edf8');
  document.addEventListener('mouseup',()=>cursor.style.background='#83b6ce55');
 });
});
const page = await context.newPage();
const start = performance.now();
const marks={};
const mark = name => { marks[name]=(performance.now()-start)/1000; console.log(`${name}: ${marks[name].toFixed(2)}s`); };
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let pointer={x:800,y:200};
async function point(locator,duration=600) {
 const box=await locator.boundingBox();
 const target={x:box.x+Math.min(box.width*.4,200),y:box.y+Math.min(box.height*.4,35)};
 const from={...pointer};
 for(let i=1;i<=30;i++) {
  const t=i/30, ease=t*t*(3-2*t);
  pointer={x:from.x+(target.x-from.x)*ease,y:from.y+(target.y-from.y)*ease};
  await page.mouse.move(pointer.x,pointer.y);
  await wait(duration/30);
 }
}
page.on('pageerror',error=>console.error('Browser:',error.message));
page.on('dialog',dialog=>dialog.dismiss());
try {
 await page.goto('https://translate.shiroko.tools/app.html',{waitUntil:'networkidle'});
 await page.locator('.editor-layout').evaluate(el=>window.scrollTo(0,el.getBoundingClientRect().top+scrollY-24));
 await wait(500);
 mark('editor');
 await point(page.locator('#source-text'),300);
 await page.locator('#source-text').click();
 await page.keyboard.insertText(passage);
 await page.locator('#source-text').press('Control+Home');
 await wait(600);
 await point(page.locator('#target-lang'),400);
 await page.locator('#target-lang').selectOption('French');
 await page.locator('#custom-instructions').fill('Preserve the literary voice. Keep the name Ishmael as written.');
 await wait(700);
 mark('submit');
 await page.locator('#translate-btn').scrollIntoViewIfNeeded();
 await point(page.locator('#translate-btn'),500);
 await page.locator('#translate-btn').click();
 await page.waitForURL('**/result.html');
 mark('loading');
 await page.locator('#processing-status').filter({hasText:'Translation Complete.'}).waitFor({timeout:180000});
 await page.locator('.alignment-row').first().waitFor();
 mark('completed');
 await page.locator('.column-headings').evaluate(el=>window.scrollTo({top:el.getBoundingClientRect().top+scrollY-24,behavior:'smooth'}));
 await wait(1000);
 mark('reveal');
 await wait(700);
 await point(page.locator('.source-item').first(),700);
 await wait(500);
 await point(page.locator('.target-item').first(),850);
 await wait(600);
 mark('compare');
 await point(page.locator('.source-item').nth(1),650);
 await page.locator('.source-item').nth(1).click({clickCount:3});
 await wait(1000);
 await point(page.locator('.target-item').nth(1),650);
 await page.locator('.target-item').nth(1).click({clickCount:3});
 await wait(900);
 await page.locator('.column-headings').click();
 await page.evaluate(()=>window.scrollBy({top:210,behavior:'smooth'}));
 await wait(1500);
 mark('scroll');
 await page.evaluate(()=>window.scrollBy({top:-210,behavior:'smooth'}));
 await wait(900);
 mark('edit');
 await point(page.locator('.target-item').first(),500);
 const target=page.locator('.target-item').first();
 await target.click();
 await target.press('Control+A');
 await wait(350);
 await target.pressSequentially('On m’appelle Ishmael.',{delay:65});
 await page.locator('.column-headings').click();
 await wait(700);
 mark('done');
 await point(page.locator('.source-item').nth(2),600);
 await point(page.locator('.target-item').nth(2),850);
 await wait(2000);
 const rows=await page.locator('.alignment-row').evaluateAll(nodes=>nodes.map(row=>({source:row.querySelector('.source-item').textContent,target:row.querySelector('.target-item').textContent})));
 if(rows.length<7||rows[0].source!=='Call me Ishmael.')throw new Error('Expected Moby-Dick aligned rows.');
 await writeFile(`${output}/aligned-result.json`,JSON.stringify(rows,null,2));
 mark('end');
 const recording=page.video();
 await context.close();
 const video=await recording.path();
 await writeFile(`${output}/recording.json`,JSON.stringify({video,marks,source:'Moby-Dick, Chapter 1 — Herman Melville',targetLanguage:'French',duration:23,drop:6,endCard:20},null,2));
 console.log(`Recorded real translation process: ${video}`);
} finally {await browser.close();}
